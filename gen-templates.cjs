const fs = require('fs');
const path = 'D:/Codex/抖音火花助手-multi/poc';
const outDir = 'D:/Codex/抖音火花助手-multi/app/supabase/functions/_shared';
const qr = JSON.parse(fs.readFileSync(path + '/anonymous-qrcode-params.json', 'utf8'));
const ck = JSON.parse(fs.readFileSync(path + '/anonymous-check-params.json', 'utf8'));
const sendFile = fs.readdirSync(path + '/captured4').find(f => f.startsWith('send-'));
const send = JSON.parse(fs.readFileSync(path + '/captured4/' + sendFile, 'utf8'));
const cookies = JSON.parse(fs.readFileSync(path + '/captured2/cookies.json', 'utf8'));
const jar = cookies.filter(c => c.name && c.value).map(c => `${c.name}=${c.value}`).join('; ');
const [sendBase, sendQs] = send.url.split('?');
const sp = new URLSearchParams(sendQs);
const sendOrder = [];
for (const [k] of new URLSearchParams(sendQs)) { if (k !== 'a_bogus') sendOrder.push(k); }
const sendStatic = {};
for (const k of sendOrder) sendStatic[k] = sp.get(k);
const lines = [];
lines.push('// 抓包模板（敏感：含会话身份令牌与设备加密块）— 禁止提交 git，仅随函数部署上传');
lines.push('// 来源：poc/captured2、captured4、anonymous-*.json（2026-08-28 验证）');
lines.push('');
lines.push('export const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/151.0.0.0 Safari/537.36";');
lines.push('');
lines.push('export const BASE_COOKIES = ' + JSON.stringify(jar) + ';');
lines.push('');
lines.push('// get_qrcode 模板参数（保持顺序，仅替换 p_ts 并重算 a_bogus）');
lines.push('export const QR_TEMPLATE_URL = ' + JSON.stringify(qr.url) + ';');
lines.push('');
lines.push('// check_qrconnect 模板参数（必须保持原样，只替换 post 中的 token）');
lines.push('export const CHECK_TEMPLATE_URL = ' + JSON.stringify(ck.url) + ';');
lines.push('export const CHECK_POST = ' + JSON.stringify(ck.post) + ';');
lines.push('');
lines.push('// 发送接口模板：URL 静态参数顺序 + postDataB64（protobuf 体）');
lines.push('export const SEND_BASE = ' + JSON.stringify(sendBase) + ';');
lines.push('export const SEND_STATIC_PARAMS = ' + JSON.stringify(sendStatic) + ';');
lines.push('export const SEND_POST_DATA_B64 = ' + JSON.stringify(send.postDataB64) + ';');
lines.push('');
lines.push('export const SEND_STATIC_PARAM_ORDER = ' + JSON.stringify(sendOrder) + ';');
fs.writeFileSync(outDir + '/templates.ts', lines.join('\n'));
console.log('generated templates.ts, bytes =', lines.join('\n').length);
